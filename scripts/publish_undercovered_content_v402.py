def validate_catalog() -> None:
    if len(TOPICS) != 100:
        raise SystemExit("The catalog must contain exactly 100 pages")
    distribution = Counter(item["section"] for item in TOPICS)
    if dict(distribution) != EXPECTED_DISTRIBUTION:
        raise SystemExit(f"Wrong distribution: {dict(distribution)}")
    routes = [route_for(item) for item in TOPICS]
    if len(set(routes)) != 100 or len({item["title"] for item in TOPICS}) != 100:
        raise SystemExit("Routes and titles must be unique")
    required = {"section", "profile", "slug", "title", "objective"}
    for item in TOPICS:
        missing = required - set(item)
        if missing:
            raise SystemExit(f"{item.get('slug')}: missing {sorted(missing)}")
        if item["profile"] not in PROFILE_BLUEPRINTS or item["profile"] not in PROFILE_SOURCES:
            raise SystemExit(f"{item['slug']}: unsupported profile")
        if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", item["slug"]):
            raise SystemExit(f"{item['slug']}: invalid slug")


def ensure_urlset(path: Path, urls: list[str]) -> int:
    namespace = "http://www.sitemaps.org/schemas/sitemap/0.9"
    ET.register_namespace("", namespace)
    if path.is_file():
        tree = ET.parse(path)
        root = tree.getroot()
        if root.tag.rsplit("}", 1)[-1] != "urlset":
            raise SystemExit(f"{path} is not a URL-set sitemap")
    else:
        root = ET.Element(f"{{{namespace}}}urlset")
        tree = ET.ElementTree(root)
    existing = {(row.findtext("{*}loc") or "").strip() for row in root.findall("{*}url")}
    added = 0
    for url in urls:
        if url in existing:
            continue
        row = ET.SubElement(root, f"{{{namespace}}}url")
        ET.SubElement(row, f"{{{namespace}}}loc").text = url
        ET.SubElement(row, f"{{{namespace}}}lastmod").text = REVIEWED_AT
        ET.SubElement(row, f"{{{namespace}}}changefreq").text = "monthly"
        ET.SubElement(row, f"{{{namespace}}}priority").text = "0.82"
        existing.add(url)
        added += 1
    rows = sorted(root.findall("{*}url"), key=lambda row: row.findtext("{*}loc") or "")
    root[:] = rows
    ET.indent(tree, space="  ")
    path.parent.mkdir(parents=True, exist_ok=True)
    tree.write(path, encoding="utf-8", xml_declaration=True)
    return added


