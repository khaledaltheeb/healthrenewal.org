def specialized_check(item: dict[str, str]) -> str:
    haystack = f"{item['slug']} {item['title']}".lower()
    for keywords, heading, points in SPECIAL_CHECKS:
        if any(keyword in haystack for keyword in keywords):
            rows = "".join(f"<li>{core.esc(point)}</li>" for point in points)
            return f'<aside class="notice topic-check"><h2>{core.esc(heading)}</h2><ul>{rows}</ul></aside>'
    profile = core.resolved_context(item)
    return (
        '<aside class="notice topic-check"><h2>تحقق تخصصي قبل اعتماد القرار</h2><ul>'
        f'<li>راجع أن السياق المحدد هو: {core.esc(profile["setting"])}.</li>'
        f'<li>راجع أن المؤشر الأساسي هو: {core.esc(profile["measure"])}.</li>'
        f'<li>امنع الخطر التالي بصورة صريحة: {core.esc(profile["risk"])}.</li>'
        '<li>وثق رأي الشخص وسبب الاستمرار أو التعديل أو الإحالة.</li></ul></aside>'
    )


def render_page(item: dict[str, str]) -> str:
    source = _ORIGINAL_RENDER(item)
    title = item["title"]
    objective = item["objective"]
    profile = core.resolved_context(item)
    replacements = {
        f"يتناول الدليل التطبيق داخل {profile['setting']}": f"يتناول الدليل التطبيق في {profile['setting']}",
        f"يستحق {title} صفحة مستقلة": f"يستحق موضوع «{title}» معالجة مستقلة",
        f"قياس {title} يجب أن يشمل": f"قياس نتائج خطة «{title}» يجب أن يشمل",
        f"متى ينجح {objective} بالفعل، وما المختلف في تلك اللحظات؟": f"في أي ظروف يتحقق الهدف «{objective}»، وما الذي يختلف بين فرصة ناجحة وأخرى متعثرة؟",
        f"أي جزء من {profile['setting']} يضيف حاجزًا يمكن تغييره؟": f"ما الحاجز الأكثر تأثيرًا في {profile['setting']}، وهل يقع في المهمة أم المكان أم التواصل أم استجابة الشريك؟",
        f"عند تحليل {title} في مجال": f"عند تحليل موضوع «{title}» في مجال",
        f"يرتبط مباشرة بـ{title}": f"يرتبط مباشرة بموضوع «{title}»",
        f"بالنسبة لهدف «{objective}»": f"عند متابعة الهدف «{objective}»",
    }
    for old, new in replacements.items():
        source = source.replace(old, new)
    marker = "<section><h2>17. أسئلة شائعة</h2>"
    if marker not in source:
        raise SystemExit(f"{item['slug']}: FAQ insertion marker missing")
    source = source.replace(marker, specialized_check(item) + marker, 1)
    return source


def publish(site: Path) -> dict[str, Any]:
    previous_render = core.render_page
    previous_revision = core.ENGINE_REVISION
    core.render_page = render_page
    core.ENGINE_REVISION = ENGINE_REVISION
    try:
        report = core.publish(site)
    finally:
        core.render_page = previous_render
        core.ENGINE_REVISION = previous_revision
    report["engine_revision"] = ENGINE_REVISION
    report["specialized_safety_check_pages"] = report["page_count"]
    report["quality_gates"]["language_editor_pass"] = True
    report["quality_gates"]["specialized_safety_checks"] = True
    api = site / "api" / "undercovered-content-v401.json"
    api.write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
    return report


def main() -> int:
    import argparse

    parser = argparse.ArgumentParser(description="Publish the edited v403 revision of the 100-page v401 contract.")
    parser.add_argument("site", type=Path)
    args = parser.parse_args()
    site = args.site.resolve()
    if not site.is_dir():
        raise SystemExit(f"Missing site directory: {site}")
    print(json.dumps(publish(site), ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
