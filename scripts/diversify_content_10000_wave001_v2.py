def visible_title(source: str) -> str:
    match = re.search(r"<h1[^>]*>(.*?)</h1>", source, re.S | re.I)
    if not match:
        match = re.search(r"<title>(.*?)</title>", source, re.S | re.I)
    text = re.sub(r"<[^>]+>", " ", match.group(1) if match else "هذه الصفحة")
    return re.sub(r"\s+", " ", html.unescape(text)).strip()


def detect_intent(slug: str) -> str:
    for key in INTENT_PLAYBOOKS:
        if slug.endswith("-" + key):
            return key
    raise ValueError(f"Unknown intent slug: {slug}")


def enrich(path: Path) -> None:
    source = path.read_text(encoding="utf-8")
    if MARKER in source:
        return
    slug = path.parent.name
    intent = detect_intent(slug)
    title = visible_title(source)
    paragraphs = []
    for idx, guidance in enumerate(INTENT_PLAYBOOKS[intent], start=1):
        paragraphs.append(
            f"<p><strong>عدسة القرار {idx} — {html.escape(title)}:</strong> {html.escape(guidance)} "
            f"طبّق هذه العدسة تحديدًا على سؤال الصفحة الحالية، واكتب مثالًا واقعيًا واحدًا وما المعلومة التي قد تغيّر الاستنتاج.</p>"
        )
    block = (
        MARKER
        + '<section class="card content-10000-wave001-v2" data-editorial-v2>'
        + '<h2>ملف قرار خاص بهذه الصفحة</h2>'
        + '<p>هذا القسم يميّز المهمة التعليمية لهذه الصفحة عن بقية صفحات الموضوع. لا تستخدمه كاختبار ذاتي للتشخيص؛ استخدمه لبناء وصف أدق، قرار أكثر قابلية للمراجعة، وأسئلة أفضل للمختص.</p>'
        + "".join(paragraphs)
        + "</section>"
    )
    if "</main>" not in source:
        raise ValueError(f"Missing </main>: {path}")
    source = source.replace("</main>", block + "</main>", 1)
    path.write_text(source, encoding="utf-8")


def main() -> None:
    pages = sorted(SECTION.glob("*/index.html"))
    if len(pages) != 66:
        raise SystemExit(f"Expected 66 wave001 pages, found {len(pages)}")
    for page in pages:
        enrich(page)
    print({"status": "enriched", "pages": len(pages), "marker": MARKER})


if __name__ == "__main__":
    main()
