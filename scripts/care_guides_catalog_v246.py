def institutional_guides() -> list[dict]:
    topics = [*TOPICS_1, *TOPICS_2, *TOPICS_3, *TOPICS_4]
    if len(topics) != EXPECTED_GUIDES:
        raise RuntimeError(f"Expected {EXPECTED_GUIDES} institutional guide specs, found {len(topics)}")
    guides = [_build(topic) for topic in topics]
    slugs = [guide["slug"] for guide in guides]
    titles = [guide["title"] for guide in guides]
    if len(slugs) != len(set(slugs)) or len(titles) != len(set(titles)):
        raise RuntimeError("Institutional care-guide specs contain duplicate slugs or titles")
    return guides
