def apply(topics: list[dict[str, Any]]) -> dict[str, Any]:
    """Merge reviewed supplements into matching topics and return diagnostics."""
    by_slug = {topic.get("slug"): topic for topic in topics}
    applied: list[str] = []
    missing: list[str] = []
    additions = 0

    for slug, patch in OVERRIDES.items():
        topic = by_slug.get(slug)
        if topic is None:
            missing.append(slug)
            continue
        for field, values in patch.items():
            current = topic.setdefault(field, [])
            if not isinstance(current, list):
                raise TypeError(f"override field must target a list: {slug}.{field}")
            for value in values:
                if value not in current:
                    current.append(value)
                    additions += 1
        applied.append(slug)

    return {
        "schemaVersion": 1,
        "status": "passed" if not missing else "warning",
        "applied": applied,
        "missing": missing,
        "additions": additions,
    }
